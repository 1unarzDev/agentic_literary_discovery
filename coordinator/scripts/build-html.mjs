const esc = (s) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
function inline(s) {
  const kbd = [];
  s = s.replace(/<kbd>(.*?)<\/kbd>/g, (_, k) => `\u0000${kbd.push(k) - 1}\u0000`);
  s = esc(s);
  s = s.replace(/`([^`]+)`/g, "<code>$1</code>");
  s = s.replace(/\*\*([^*]+)\*\*/g, "<strong>$1</strong>");
  s = s.replace(/(^|[^*\w])\*([^*\s][^*]*)\*/g, "$1<em>$2</em>");
  s = s.replace(/\[([^\]]+)\]\(([^)\s]+)\)/g, (_, t, u) => `<a href="${u}">${t}</a>`);
  return s.replace(/\u0000(\d+)\u0000/g, (_, i) => `<kbd>${esc(kbd[+i])}</kbd>`);
}
const slug = (s) => s.toLowerCase().replace(/<[^>]+>/g, "").replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");

export function renderMarkdown(md) {
  const lines = md.replace(/\r/g, "").split("\n");
  const out = [];
  const toc = [];
  let i = 0;
  const para = [];
  const flush = () => {
    if (para.length) out.push(`<p>${inline(para.join(" "))}</p>`);
    para.length = 0;
  };
  while (i < lines.length) {
    const l = lines[i];
    let m;
    if (!l.trim()) { flush(); i++; continue; }
    if (/^<!--/.test(l.trim())) { flush(); while (i < lines.length && !lines[i].includes("-->")) i++; i++; continue; }
    if ((m = /^(#{1,4})\s+(.*)$/.exec(l))) {
      flush();
      const n = m[1].length, t = inline(m[2]), id = slug(m[2]);
      if (n === 2) toc.push(`<a href="#${id}">${t}</a>`);
      out.push(`<h${n} id="${id}">${t}</h${n}>`);
      i++; continue;
    }
    if (/^---+\s*$/.test(l)) { flush(); out.push("<hr>"); i++; continue; }
    if (/^>\s?/.test(l)) {
      flush();
      const q = [];
      while (i < lines.length && /^>/.test(lines[i])) { q.push(lines[i].replace(/^>\s?/, "")); i++; }
      out.push(`<blockquote>${renderMarkdown(q.join("\n")).body}</blockquote>`);
      continue;
    }
    if (/^\|/.test(l)) {
      flush();
      const rows = [];
      while (i < lines.length && /^\|/.test(lines[i])) { rows.push(lines[i]); i++; }
      const cells = (r) => r.trim().replace(/^\||\|$/g, "").split("|").map((c) => inline(c.trim()));
      const head = cells(rows[0]);
      const body = rows.slice(2).map(cells);
      out.push(
        `<div class="tw"><table><thead><tr>${head.map((h) => `<th>${h}</th>`).join("")}</tr></thead><tbody>` +
          body.map((r) => `<tr>${r.map((c) => `<td>${c}</td>`).join("")}</tr>`).join("") +
          "</tbody></table></div>",
      );
      continue;
    }
    if ((m = /^(\s*)([-*]|\d+\.)\s+/.exec(l))) {
      flush();
      const ordered = /\d/.test(m[2]);
      const items = [];
      while (i < lines.length && (m = /^(\s*)([-*]|\d+\.)\s+(.*)$/.exec(lines[i]))) {
        let t = m[3];
        i++;
        while (i < lines.length && lines[i].trim() && /^\s{2,}\S/.test(lines[i]) && !/^\s*([-*]|\d+\.)\s+/.test(lines[i])) {
          t += " " + lines[i].trim();
          i++;
        }
        items.push(`<li>${inline(t)}</li>`);
      }
      out.push(ordered ? `<ol>${items.join("")}</ol>` : `<ul>${items.join("")}</ul>`);
      continue;
    }
    para.push(l.trim());
    i++;
  }
  flush();
  return { body: out.join("\n"), toc };
}

